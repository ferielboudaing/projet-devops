CREATE DATABASE IF NOT EXISTS nova_db CHARACTER SET utf8 COLLATE utf8_general_ci;
USE nova_db;
CREATE TABLE IF NOT EXISTS classes (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL, level VARCHAR(50) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8;
CREATE TABLE IF NOT EXISTS users (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL, email VARCHAR(150) NOT NULL UNIQUE,
 password VARCHAR(255) NOT NULL, role ENUM('admin','enseignant','etudiant') NOT NULL,
 active TINYINT(1) NOT NULL DEFAULT 1, class_id INT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, INDEX idx_user_class(class_id),
 FOREIGN KEY(class_id) REFERENCES classes(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8;
CREATE TABLE IF NOT EXISTS subjects (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL, code VARCHAR(30) NOT NULL UNIQUE,
 coefficient DECIMAL(4,1) NOT NULL DEFAULT 1, semester VARCHAR(10) NOT NULL,
 td_weight DECIMAL(5,4) NOT NULL DEFAULT 0.2000,
 tp_weight DECIMAL(5,4) NOT NULL DEFAULT 0.2000,
 exam_weight DECIMAL(5,4) NOT NULL DEFAULT 0.6000
) ENGINE=InnoDB DEFAULT CHARSET=utf8;
CREATE TABLE IF NOT EXISTS grades (
 id INT AUTO_INCREMENT PRIMARY KEY, student_id INT NOT NULL, subject_id INT NOT NULL,
 evaluation ENUM('TD','TP','Examen') NOT NULL, score DECIMAL(4,2) NOT NULL,
 created_by INT NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY unique_student_subject_eval(student_id,subject_id,evaluation),
 FOREIGN KEY(student_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(subject_id) REFERENCES subjects(id) ON DELETE CASCADE,
 FOREIGN KEY(created_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8;
